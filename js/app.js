function fillModal(project) {
  const title = document.getElementById("modalTitle");
  const desc = document.getElementById("modalDesc");
  const image = document.getElementById("modalImage");
  const tags = document.getElementById("modalTags");
  const links = document.getElementById("modalLinks");
  if (!title || !desc || !image || !tags || !links) return;

  title.textContent = project.title;
  desc.textContent = t(project.descKey);
  image.src = project.image;
  image.alt = project.title;
  tags.replaceChildren(
    ...project.tags.map((name) => {
      const tag = document.createElement("span");
      tag.className = "tech-tag";
      tag.textContent = name;
      return tag;
    }),
  );

  const github = document.createElement("a");
  github.href = project.github;
  github.target = "_blank";
  github.rel = "noopener";
  github.textContent = t("projects.github");

  const demo = document.createElement("a");
  demo.href = project.demo;
  demo.target = "_blank";
  demo.rel = "noopener";
  demo.textContent = t("projects.demo");

  links.replaceChildren(github, demo);
}

function initProjectModal() {
  const overlay = document.getElementById("projectModal");
  const closeBtn = document.getElementById("modalClose");
  if (!overlay || !closeBtn) return;

  let lastFocus = null;

  const open = (id) => {
    const project = PROJECTS[id];
    if (!project) return;
    lastFocus = document.activeElement;
    activeProjectId = id;
    fillModal(project);
    overlay.classList.add("is-open");
    overlay.setAttribute("aria-hidden", "false");
    document.body.classList.add("modal-open");
    closeBtn.focus();
  };

  const close = () => {
    overlay.classList.remove("is-open");
    overlay.setAttribute("aria-hidden", "true");
    document.body.classList.remove("modal-open");
    activeProjectId = null;
    if (lastFocus && typeof lastFocus.focus === "function") lastFocus.focus();
  };

  document.querySelectorAll("[data-project]").forEach((card) => {
    const openCard = () => open(card.dataset.project);
    card.addEventListener("click", (e) => {
      if (e.target.closest("a")) return;
      openCard();
    });
    card.addEventListener("keydown", (e) => {
      if (e.key === "Enter" || e.key === " ") {
        e.preventDefault();
        openCard();
      }
    });
  });

  closeBtn.addEventListener("click", close);
  overlay.addEventListener("click", (e) => {
    if (e.target === overlay) close();
  });
  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape" && overlay.classList.contains("is-open")) close();
  });
}

