function closeNav() {
  const navbarEl = document.getElementById("navbar");
  const navToggle = document.getElementById("navToggle");
  if (!navbarEl || !navToggle) return;
  navbarEl.classList.remove("nav-open");
  navToggle.classList.remove("active");
  navToggle.setAttribute("aria-expanded", "false");
}

function initNav() {
  const navbarEl = document.getElementById("navbar");
  const navToggle = document.getElementById("navToggle");
  const navMenu = document.getElementById("navMenu");
  if (!navbarEl || !navToggle || !navMenu) return;

  navToggle.addEventListener("click", () => {
    const isOpen = navbarEl.classList.toggle("nav-open");
    navToggle.classList.toggle("active", isOpen);
    navToggle.setAttribute("aria-expanded", isOpen ? "true" : "false");
  });

  navMenu.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", closeNav);
  });

  const desktopQuery = window.matchMedia("(min-width: 1025px)");
  const onBreakpoint = (e) => {
    if (e.matches) closeNav();
  };
  if (desktopQuery.addEventListener) {
    desktopQuery.addEventListener("change", onBreakpoint);
  } else {
    desktopQuery.addListener(onBreakpoint);
  }
}

function initNavCompact() {
  const navbarEl = document.getElementById("navbar");
  const sentinel = document.getElementById("navSentinel");
  if (!navbarEl || !sentinel || !("IntersectionObserver" in window)) return;

  const observer = new IntersectionObserver(
    ([entry]) => {
      navbarEl.classList.toggle("is-compact", !entry.isIntersecting);
    },
    { threshold: 0 },
  );
  observer.observe(sentinel);
}

function initReveals() {
  const nodes = document.querySelectorAll(".reveal");
  if (!nodes.length) return;

  if (prefersReducedMotion || !("IntersectionObserver" in window)) {
    nodes.forEach((el) => el.classList.add("is-visible"));
    return;
  }

  const observer = new IntersectionObserver(
    (entries, obs) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("is-visible");
        obs.unobserve(entry.target);
      });
    },
    { threshold: 0.12, rootMargin: "0px 0px -48px 0px" },
  );

  nodes.forEach((el) => observer.observe(el));
}

function initLazyImages() {
  const images = document.querySelectorAll("img[data-src]");
  if (!images.length) return;

  const loadImage = (img) => {
    const src = img.getAttribute("data-src");
    if (!src || img.dataset.loaded === "true") return;
    img.dataset.loaded = "true";
    img.src = src;
    const reveal = () => img.classList.add("is-loaded");
    if (img.complete) reveal();
    else img.addEventListener("load", reveal, { once: true });
    img.addEventListener("error", reveal, { once: true });
  };

  if (!("IntersectionObserver" in window)) {
    images.forEach(loadImage);
    return;
  }

  const observer = new IntersectionObserver(
    (entries, obs) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        loadImage(entry.target);
        obs.unobserve(entry.target);
      });
    },
    { rootMargin: "240px 0px" },
  );

  images.forEach((img) => observer.observe(img));
}

function initWorkspaceTilt() {
  const wsShowcase = document.getElementById("workspaceShowcase");
  const wsScene = document.getElementById("wsScene");
  if (!wsShowcase || !wsScene || prefersReducedMotion) return;

  wsShowcase.addEventListener("mousemove", (e) => {
    const r = wsShowcase.getBoundingClientRect();
    const px = (e.clientX - r.left) / r.width - 0.5;
    const py = (e.clientY - r.top) / r.height - 0.5;
    wsScene.style.setProperty("--ry", `${px * 34 - 22}deg`);
    wsScene.style.setProperty("--rx", `${18 - py * 22}deg`);
  });

  wsShowcase.addEventListener("mouseleave", () => {
    wsScene.style.setProperty("--ry", "-22deg");
    wsScene.style.setProperty("--rx", "18deg");
  });
}

