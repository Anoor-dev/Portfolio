const root = document.documentElement;
const prefersReducedMotion = window.matchMedia(
  "(prefers-reduced-motion: reduce)",
).matches;

const getLang = () => (root.getAttribute("lang") === "fa" ? "fa" : "en");
const t = (key) => I18N[getLang()][key] || I18N.en[key] || key;

let activeProjectId = null;

function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = t(key);
    if (value) el.textContent = value;
  });

  const langToggle = document.getElementById("langToggle");
  if (langToggle) langToggle.textContent = getLang() === "fa" ? "EN" : "FA";

  root.classList.remove("i18n-pending");

  if (activeProjectId && PROJECTS[activeProjectId]) {
    fillModal(PROJECTS[activeProjectId]);
  }
}

function setLang(lang) {
  root.setAttribute("lang", lang);
  root.setAttribute("dir", lang === "fa" ? "rtl" : "ltr");
  localStorage.setItem("lang", lang);
  applyI18n();
}

const intro = document.getElementById("intro");
const introPercent = document.getElementById("introPercent");
const introBar = document.getElementById("introBar");
const introStatus = document.getElementById("introStatus");

const statuses = [
  "Loading interface...",
  "Preparing components...",
  "Initializing animations...",
  "Loading projects...",
  "Almost ready...",
  "System ready.",
];

let progress = 0;

function runIntro() {
  const interval = setInterval(() => {
    progress += Math.floor(Math.random() * 8) + 3;

    if (progress >= 100) {
      progress = 100;
      clearInterval(interval);

      introPercent.textContent = "100%";
      introBar.style.width = "100%";
      introStatus.textContent = "System ready.";

      setTimeout(exitIntro, 500);
      return;
    }

    introPercent.textContent = `${progress}%`;
    introBar.style.width = `${progress}%`;

    const index = Math.floor((progress / 100) * statuses.length);

    introStatus.textContent = statuses[Math.min(index, statuses.length - 1)];
  }, 120);
}

function exitIntro() {
  intro.classList.add("intro-exit");

  setTimeout(() => {
    intro.remove();
  }, 800);
}

function switchTheme() {
  const isDark = root.classList.contains("dark");

  root.classList.toggle("dark", !isDark);

  localStorage.setItem("theme", !isDark ? "dark" : "light");
}

function changeTheme() {
  const isDark = root.classList.contains("dark");

  root.classList.toggle("theme-transition-to-dark", !isDark);

  root.classList.toggle("theme-transition-to-light", isDark);

  const updateTheme = () => {
    switchTheme();
  };

  if (document.startViewTransition) {
    const transition = document.startViewTransition(updateTheme);

    transition.finished.finally(() => {
      root.classList.remove(
        "theme-transition-to-dark",
        "theme-transition-to-light",
      );
    });
  } else {
    updateTheme();

    setTimeout(() => {
      root.classList.remove(
        "theme-transition-to-dark",
        "theme-transition-to-light",
      );
    }, 600);
  }
}

